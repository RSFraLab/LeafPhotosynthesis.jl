# Tiny serializer for this documentation's strings, finite numbers, and tables.
# No JSON/plotting dependency is added to the physiology package.
function json(value::AbstractString)
    escaped = replace(value, r"[\\\"\x00-\x1f]" => s ->
        s == "\\" ? "\\\\" : s == "\"" ? "\\\"" :
        "\\u" * string(Int(first(s)); base = 16, pad = 4))
    return "\"" * escaped * "\""
end
json(value::Real) = isfinite(value) ? string(Float64(value)) : error("Nonfinite plot data")
json(value::Bool) = value ? "true" : "false"
json(value::AbstractVector) = "[" * join(json.(value), ",") * "]"
json(value::NamedTuple) = json(Dict(string(k) => v for (k, v) in pairs(value)))
json(value::AbstractDict) = "{" * join((json(k) * ":" * json(value[k]) for k in sort!(collect(keys(value)))), ",") * "}"

function build_examples()
    parameter_dir = joinpath(@__DIR__, "..", "examples", "parameters")
    data = Dict{String,Any}()
    for FT in (Float32, Float64)
        biochemistry = read_bonan_parameters(FT, joinpath(parameter_dir, "bonan_11_1.toml"))
        settings = read_bonan_parameters(FT, joinpath(parameter_dir, "core_exchange.toml"))
        curves = bonan_curves(FT, biochemistry)
        stomata = stomatal_response(FT, biochemistry, settings)
        result = equilibrium_example(FT, biochemistry, settings)
        equilibrium = (; conductance = result.exchange.stomatal_conductance,
            net_assimilation = result.exchange.carbon.net_assimilation,
            net_oxygen = result.oxygen.net_release, transpiration = result.water.transpiration,
            dA_dgs = result.carbon.dnet_assimilation_dgs, dE_dgs = result.water.dtranspiration_dgs,
            iterations = result.exchange.iterations, converged = result.exchange.converged)
        data[string(FT)] = (; curves, stomata, equilibrium, biochemistry, settings)
        tables = Dict{String,Any}(name => rows for (name, rows) in curves)
        tables["stomata"] = stomata
        tables["equilibrium"] = [equilibrium]
        write_tables(joinpath(@__DIR__, "assets", "data", string(FT)), tables)
    end
    sources = Dict(name => read(joinpath(@__DIR__, "..", "examples", name * ".jl"), String)
        for name in ("one_leaf", "bonan_11_1", "core_exchange", "stomatal_response"))
    payload = (; data, sources, julia_version = string(VERSION))
    open(joinpath(@__DIR__, "assets", "examples-data.js"), "w") do io
        println(io, "// Generated by docs/build_examples.jl; do not edit by hand.")
        println(io, "window.leafExamples = ", json(payload), ";")
    end
    println("Open docs/examples.html in a browser. All scripts and data are local.")
end

if abspath(PROGRAM_FILE) == @__FILE__
    build_examples()
end
