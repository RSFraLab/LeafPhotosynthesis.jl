# Tiny serializer for this documentation's strings, finite numbers, and tables.
# No JSON/plotting dependency is added to the physiology package.
function json(value::AbstractString)
    escaped = replace(value, r"[\\\"\x00-\x1f]" => s ->
        s == "\\" ? "\\\\" : s == "\"" ? "\\\"" :
        "\\u" * string(Int(first(s)); base = 16, pad = 4))
    return "\"" * escaped * "\""
end
json(value::Real) = isfinite(value) ? string(Float64(value)) : error("Nonfinite plot data")
json(value::Bool) = value ? "true" : "false"
json(::Nothing) = "null" # Explicit absent dark yields, not arbitrary nonfinite values.
json(value::AbstractVector) = "[" * join(json.(value), ",") * "]"
json(value::NamedTuple) = json(Dict(string(k) => v for (k, v) in pairs(value)))
json(value::AbstractDict) = "{" * join((json(k) * ":" * json(value[k]) for k in sort!(collect(keys(value)))), ",") * "}"

"""
    write_gallery_data(dir) -> (; data, flexas)

Run the examples in both precisions and write the chart data and CSV tables into `dir`.
Return the payloads (Julia values) for [`check_gallery_data`](@ref).
"""
function write_gallery_data(dir)
    parameter_dir = joinpath(EXAMPLES, "parameters")
    data = Dict{String,Any}()
    for FT in (Float32, Float64)
        biochemistry = read_bonan_parameters(FT, joinpath(parameter_dir, "bonan_11_1.toml"))
        settings = read_bonan_parameters(FT, joinpath(parameter_dir, "core_exchange.toml"))
        curves = bonan_curves(FT, biochemistry)
        stomata = stomatal_response(FT, biochemistry, settings)
        turnover = turnover_response(FT)
        oxygen_response_rows = oxygen_response(FT)
        fluorescence_rows = fluorescence_response(FT)
        cytochrome_stress = cytochrome_stress_curves(FT)
        johnson_berry = johnson_berry_2021_curves(FT)
        flexas_2002 = flexas_2002_curves(FT)
        gu_2019 = gu_2019_curves(FT)
        turnover_settings = read_bonan_parameters(FT, joinpath(parameter_dir, "turnover.toml"))
        result = equilibrium_example(FT, biochemistry, settings)
        is_valid(result.exchange) || error("Nonconverged equilibrium in the $FT gallery example")
        equilibrium = (; conductance = result.exchange.stomatal_conductance,
            net_assimilation = result.exchange.exchange.net_assimilation,
            net_oxygen = result.oxygen.net_release, transpiration = result.water.transpiration,
            dA_dgs = result.carbon.dnet_assimilation_dgs, dE_dgs = result.water.dtranspiration_dgs,
            iterations = result.exchange.iterations, converged = is_valid(result.exchange))
        data[string(FT)] = (; curves, stomata, turnover, turnover_settings, oxygen_response = oxygen_response_rows,
            fluorescence = fluorescence_rows, cytochrome_stress, johnson_berry, flexas_2002, gu_2019, equilibrium, biochemistry, settings)
        tables = Dict{String,Any}(name => rows for (name, rows) in curves)
        tables["stomata"] = stomata
        tables["equilibrium"] = [equilibrium]
        tables["turnover"] = turnover
        tables["oxygen_response"] = oxygen_response_rows
        tables["fluorescence"] = fluorescence_rows
        merge!(tables, Dict(cytochrome_stress), Dict(johnson_berry), Dict(flexas_2002), Dict(gu_2019))
        write_tables(joinpath(dir, "data", string(FT)), tables)
    end
    sources = Dict(name => read(joinpath(EXAMPLES, name * ".jl"), String) for name in SOURCES)
    payload = (; data, sources, julia_version = string(VERSION))
    write(joinpath(dir, "examples-data.js"),
        "// Generated by docs/gallery_data.jl; do not edit by hand.\n",
        "window.leafExamples = ", json(payload), ";\n")
    flexas_data = Dict(
        precision => (;
            tables = data[precision].flexas_2002,
            parameters = read_bonan_parameters(
                precision == "Float32" ? Float32 : Float64,
                joinpath(parameter_dir, "flexas_2002.toml"),
            ),
        ) for precision in ("Float32", "Float64")
    )
    flexas_sources = Dict(
        "flexas_2002" => sources["flexas_2002"],
        "flexas_setup" => read(joinpath(EXAMPLES, "setup", "flexas_2002.jl"), String),
        "flexas_toml" => read(joinpath(parameter_dir, "flexas_2002.toml"), String),
    )
    flexas = (; data = flexas_data, sources = flexas_sources, julia_version = string(VERSION))
    write(joinpath(dir, "flexas-2002-data.js"),
        "// Generated by docs/gallery_data.jl; do not edit by hand.\n",
        "window.flexas2002Explorer = ", json(flexas), ";\n")
    return (; data = payload, flexas)
end

# Every key of a nested payload (dictionaries and named tuples, including table columns).
payload_keys!(keys, x) = keys
payload_keys!(keys, x::AbstractVector) = (foreach(v -> payload_keys!(keys, v), x); keys)
function payload_keys!(keys, x::Union{AbstractDict,NamedTuple})
    for (k, v) in pairs(x)
        push!(keys, string(k))
        payload_keys!(keys, v)
    end
    return keys
end

# Tables are vectors of named tuples; `nothing` marks an undefined dark-leaf ratio.
table_entries(x, path = "") = Pair{String,Any}[]
table_entries(x::AbstractVector{<:NamedTuple}, path = "") = Pair{String,Any}[path => x]
function table_entries(x::Union{AbstractDict,NamedTuple}, path = "")
    out = Pair{String,Any}[]
    for (k, v) in pairs(x)
        append!(out, table_entries(v, string(path, "/", k)))
    end
    return out
end

strip_js_comments(s) = replace(replace(s, r"/\*[\s\S]*?\*/" => ""), r"(?m)(^|\s)//.*$" => "")

# Snake-case words in a chart script are data keys (functions and DOM ids use camelCase or
# kebab-case). `g_sw` is only a column heading.
const NOT_DATA_KEYS = Set(["g_sw"])

"""
    check_gallery_data(payloads, dir, script_dir, page_dir)

Checks that replace the former browser test (docs/check_examples.cjs): every data key and
CSV table that the chart scripts reference exists, every figure a page embeds is defined,
every value is finite (`nothing` only for undefined dark-leaf ratios and absent
observations), and the documented qualitative results hold in both precisions.
"""
function check_gallery_data(payloads, dir, script_dir, page_dir)
    @testset "Documentation chart data" begin
        keys = payload_keys!(Set{String}(), payloads.data)
        payload_keys!(keys, payloads.flexas)
        gallery_js = read(joinpath(script_dir, "gallery.js"), String)
        scripts = Dict(f => strip_js_comments(read(joinpath(script_dir, f), String))
            for f in ("gallery.js", "flexas_2002.js", "loader.js"))
        @testset "data keys referenced by the scripts" begin
            for js in values(scripts)
                words = Set(m.match for m in eachmatch(r"\b[a-z][a-z0-9]*(?:_[a-z0-9]+)+\b", js))
                @test isempty(setdiff(words, keys, NOT_DATA_KEYS))
            end
        end
        csv_names = Set{String}()
        for js in values(scripts), m in eachmatch(r"(?:csv\(|file:\s*|csvFile:\s*)\"([a-z0-9_]+)\"", js)
            push!(csv_names, m.captures[1])
        end
        foreach(id -> push!(csv_names, id), ("light", "co2", "temperature")) # csv(spec.id)
        @testset "CSV tables" begin
            for FT in ("Float32", "Float64"), name in sort!(collect(csv_names))
                @test isfile(joinpath(dir, "data", FT, name * ".csv"))
            end
        end
        # Figure ids of the gallery; "paper" is the id of the background plugin.
        figure_ids = setdiff(Set(m.captures[1] for m in eachmatch(r"\bid:\s*\"([a-z0-9-]+)\"", gallery_js)), ["paper"])
        # The two Gu et al. (2019) Flexas figures pass their id to one shared specification.
        union!(figure_ids, m.captures[1] for m in eachmatch(r"guFlexasFigure\(\"([a-z0-9-]+)\"", gallery_js))
        @testset "figures embedded in pages" begin
            @test length(figure_ids) == 33
            for page in filter(endswith(".md"), readdir(page_dir))
                text = read(joinpath(page_dir, page), String)
                for m in eachmatch(r"data-figures=\"([^\"]+)\"", text), id in split(m.captures[1])
                    @test id in figure_ids
                end
            end
        end
        for FT in ("Float32", "Float64")
            check_values(payloads.data.data[FT], FT)
        end
    end
end

function check_values(d, FT)
    @testset "$FT values" begin
        @testset "finite or absent" begin
            for (path, rows) in table_entries(d), row in rows, (column, value) in pairs(row)
                if value === nothing
                    @test get(row, :dark, false) === true || column === :observed_flexas
                elseif value isa Real && !(value isa Bool)
                    @test isfinite(value)
                end
            end
        end
        @test d.equilibrium.converged
        temperatures = unique(r.temperature for r in d.oxygen_response)
        @test length(temperatures) == 3
        @test all(T -> count(r -> r.temperature == T, d.oxygen_response) == 5, temperatures)

        fl = d.fluorescence
        @test fl[1].dark && fl[1].regulated_photons == 0 && fl[1].regulated_yield === nothing

        cs = d.cytochrome_stress
        light, drought, cap = cs["cytochrome_light"], cs["cytochrome_drought"], cs["cytochrome_capacity"]
        @test light[1].dark && light[1].jb_total_photons == 0 && light[1].jb_psii_yield === nothing
        @test drought[1].high_jb_psii_yield < drought[end].high_jb_psii_yield       # drought sign
        @test drought[1].high_vdt_cotton_yield > drought[end].high_vdt_cotton_yield
        @test cap[1].jb_rubisco_psii_yield < cap[end].jb_rubisco_psii_yield         # capacity fork
        @test cap[1].jb_b6f_psii_yield > cap[end].jb_b6f_psii_yield

        jb = d.johnson_berry
        c9, c12, pam = jb["jb_connectivity"], jb["jb_capacity"], jb["jb_pam"]
        low, high = 11, 101
        @test c9[1].dark && c9[1].ku2_psii_yield === nothing
        @test c12[low].cap_05x_yield > c12[low].cap_25x_yield                       # Case 12 inversion
        @test c12[high].cap_05x_yield < c12[high].cap_25x_yield
        @test pam[low].pam_apparent_photochemical_yield < pam[low].true_psii_photochemical_yield
        @test pam[low].pam_closed_lake_1_minus_ql < pam[low].ideal_closed_lake_1_minus_ql
        @test abs(pam[low].pam_closed_puddle_1_minus_qp - pam[low].ideal_closed_puddle_1_minus_qp) < 1e-5

        fx = d.flexas_2002
        fig2, emp, inset, ctrl, dig = fx["flexas_mechanistic_fig2"], fx["flexas_empirical_fig2"],
            fx["flexas_inset_conductance"], fx["flexas_controls"], fx["flexas_digitized_fig2"]
        @test length(dig) == 55
        @test count(r -> r.observed_flexas !== nothing, inset) == 6
        @test fig2[1].g150_fs_over_fo == 1
        @test maximum(r.g150_fs_over_fo for r in fig2) > maximum(r.g10_fs_over_fo for r in fig2)
        @test fig2[end].g10_fs_over_fo < 1
        @test abs(maximum(r.cotton_g150 for r in emp[2:end]) - maximum(r.cotton_g10 for r in emp[2:end])) < 0.02
        @test emp[end].cotton_g10 > emp[end].cotton_g150
        @test inset[1].pam2000_combined < inset[end].pam2000_combined
        @test inset[1].empirical_cotton > inset[end].empirical_cotton
        @test ctrl[end].high_co2_reversion_pam > 1.3
        @test ctrl[end].dtt_unquenched > 2.3
        @test length(fx["flexas_formulation_summary"]) == 6
        connectivity, grid = fx["flexas_connectivity_fig2"], fx["flexas_connectivity_rmse"]
        @test all(r -> r.g150_ku_0p5 >= r.g150_ku_2 >= r.g150_ku_10 > 1, connectivity)
        @test connectivity[end].g10_ku_2 < 1
        @test argmin(r -> r.rmse_ku_1, grid).psi_weight > argmin(r -> r.rmse_ku_3, grid).psi_weight
        @test length(fx["flexas_conductance_summary"]) == 6

        gu = d.gu_2019
        @test length(gu["gu_vitis_light_response"]) == 8
        @test length(gu["gu_flexas_fig2"]) == 49
        rmse = Dict(r.formulation => r.lit_fig2_rmse for r in gu["gu_flexas_summary"])
        @test rmse["johnson_berry_pam2000"] < rmse["lake_model_open_fraction"] <
            rmse["lake_measured_open_fraction"]
        @test length(gu["gu_flexas_inset"]) == 6
        @test all(r -> r.fluorescence_yield < r.paper_fluorescence_yield, gu["gu_vitis_light_response"])
        @test abs(gu["gu_sif_assimilation"][end].gpp_rsb_100 - 17.47) < 0.1
    end
end

