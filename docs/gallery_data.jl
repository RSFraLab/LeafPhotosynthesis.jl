# site is built. Included by docs/make.jl; nothing here is committed output.
#
#   write_gallery_data(dir)  runs every example in Float32 and Float64 and writes
#                            dir/examples-data.js, dir/flexas-2002-data.js and the CSV
#                            tables dir/data/{Float32,Float64}/*.csv
#   check_gallery_data(...)  checks the data against the chart scripts and pages
